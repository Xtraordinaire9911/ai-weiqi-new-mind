// Service worker: keeps the app shell and data/library.js in a cache so the viewer opens offline.
// Rules: same-origin GET requests only. Anything cross-origin (bilibili links are opened by the user, the engine bridge is called by engine_net.js)
// is never touched, never cached and never answered from here. The cache name follows the visible interface version (VIEWER_VER in index.html).
'use strict';
const VER = '4.6';
const CACHE = 'joseki-shell-v' + VER;
const SHELL = ['./', 'index.html', 'mobile.js', 'pwa.js', 'engine_core.js', 'engine_net.js', 'engine_panel.js', 'quiz_core.js', 'quiz.js',
  'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png', 'icons/apple-touch-icon.png', 'data/library.js'];
const DATA = 'data/library.js'; // regenerated by the pipeline without a viewer version bump: cache first, refreshed in the background

self.addEventListener('install', e => {
  // addAll fails as a whole if one file is missing, so a broken deploy never replaces a working worker
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL.map(u => new Request(u, { cache: 'reload' })))));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('joseki-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});

// The page asks for the switch only after the user taps "update", so a running session is never changed under their hands.
self.addEventListener('message', e => { if (e.data === 'skip-waiting') self.skipWaiting(); });

function fromNet(req) { return fetch(req); } // the one network call of this file, for same-origin requests only (checked before it is reached)

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // never cross-origin: the browser handles it as usual
  e.respondWith(caches.open(CACHE).then(async c => {
    const hit = await c.match(req, { ignoreSearch: true });
    const refresh = () => fromNet(req).then(res => { if (res && res.ok && res.type === 'basic') c.put(req.url.split('?')[0], res.clone()); return res; });
    if (hit) { if (url.pathname.endsWith(DATA)) e.waitUntil(refresh().catch(() => {})); return hit; }
    try { return await refresh(); }
    catch (err) {
      if (req.mode === 'navigate') { const idx = await c.match('index.html'); if (idx) return idx; }
      return new Response('offline', { status: 503, statusText: 'offline', headers: { 'Content-Type': 'text/plain' } });
    }
  }));
});
